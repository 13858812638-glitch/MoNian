/** Deterministic offline-capable ESM -> CommonJS bundle using pinned TypeScript.
 * This is build infrastructure only. The runtime has no filesystem or Node dependency.
 * Only static local imports and the explicitly allowed Obsidian host modules are accepted.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import ts from 'typescript';
import { parse } from 'acorn';
const root=process.cwd();
export function build({entry='src/main.js',outfile='dist/main.js',defaultExport=true}={}){
 const records=new Map();const visiting=new Set();const ordered=[];
 function visit(id){
  if(visiting.has(id))throw Error('Circular import: '+[...visiting,id].join(' -> '));
  if(records.has(id))return;
  if(!fs.existsSync(id))throw Error('Unresolved module: '+id);
  visiting.add(id);
  const source=fs.readFileSync(id,'utf8');const tree=parse(source,{ecmaVersion:'latest',sourceType:'module'});const links={};
  for(const st of tree.body){
   if(st.type==='ImportDeclaration'||((st.type==='ExportNamedDeclaration'||st.type==='ExportAllDeclaration')&&st.source)){
    const spec=st.source.value;
    if(spec.startsWith('.')){
     const target=path.posix.normalize(path.posix.join(path.posix.dirname(id),spec));
     if(!target.startsWith('src/')&&!target.startsWith('tests/'))throw Error('Import outside source tree: '+spec);
     if(!target.endsWith('.js'))throw Error('Use explicit .js module extensions: '+spec);
     links[spec]=target;visit(target);
    }else{
     if(!['obsidian','electron'].includes(spec))throw Error('Unsupported runtime dependency: '+spec);
     links[spec]='@host/'+spec;
    }
   }
  }
  const result=ts.transpileModule(source,{fileName:id,reportDiagnostics:true,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2021,removeComments:false,sourceMap:false,esModuleInterop:false,newLine:ts.NewLineKind.LineFeed}});
  const errors=(result.diagnostics||[]).filter(d=>d.category===ts.DiagnosticCategory.Error);
  if(errors.length)throw Error(ts.formatDiagnosticsWithColorAndContext(errors,{getCanonicalFileName:x=>x,getCurrentDirectory:()=>root,getNewLine:()=> '\n'}));
  records.set(id,{code:result.outputText,links});visiting.delete(id);ordered.push(id);
 }
 visit(entry);
 const factories=ordered.map(id=>JSON.stringify(id)+': function(module, exports, require) {\n'+records.get(id).code+'\n}').join(',\n');
 const links=Object.fromEntries(ordered.map(id=>[id,records.get(id).links]));
 const banner='/* GLS Navigator 2026-10-15.7 | engineering picker-ios-portal.1\n * GENERATED by scripts/build.mjs + TypeScript 5.8.3. Edit src/, not this file.\n * Original manifest identity must be preserved; no manifest was supplied.\n */\n';
 const output=banner+`(function(__hostRequire) {\nconst __factories = {\n${factories}\n};\nconst __links = ${JSON.stringify(links)};\nconst __cache = Object.create(null);\nconst __hostCache = Object.create(null);\nfunction __load(id) {\n  if (Object.prototype.hasOwnProperty.call(__cache, id)) return __cache[id].exports;\n  const factory = __factories[id];\n  if (!factory) throw new Error('Unresolved bundled module: ' + id);\n  const record = { exports: {} };\n  __cache[id] = record;\n  const requireLocal = spec => {\n    const target = __links[id][spec];\n    if (!target) throw new Error('Unresolved static import: ' + id + ' -> ' + spec);\n    if (target.startsWith('@host/')) {\n      const name = target.slice(6);\n      if (!Object.prototype.hasOwnProperty.call(__hostCache, name)) __hostCache[name] = __hostRequire(name);\n      return __hostCache[name];\n    }\n    return __load(target);\n  };\n  try { factory(record, record.exports, requireLocal); } catch (error) { delete __cache[id]; throw error; }\n  return record.exports;\n}\nconst __entry = __load(${JSON.stringify(entry)});\nmodule.exports = ${defaultExport?'__entry.default':'__entry'};\n})(require);\n`;
 parse(output,{ecmaVersion:'latest',sourceType:'script'});
 fs.mkdirSync(path.dirname(outfile),{recursive:true});fs.writeFileSync(outfile,output);
 return {outfile,modules:records.size,bytes:Buffer.byteLength(output),sha256:crypto.createHash('sha256').update(output).digest('hex'),external:[...new Set(Object.values(links).flatMap(x=>Object.values(x)).filter(x=>x.startsWith('@host/')))]};
}
if(process.argv[1]&&path.resolve(process.argv[1])===path.resolve('scripts/build.mjs')){
 const info=build();fs.copyFileSync('src/styles/styles.css','dist/styles.css');
 fs.writeFileSync('reports/build-info.json',JSON.stringify({...info,engine:'TypeScript 5.8.3 + deterministic CommonJS linker',baselineBuild:'2026-10-15.7',engineeringRevision:'picker-ios-portal.1',manifestStatus:'missing-in-upload'},null,2));
 console.log(JSON.stringify(info,null,2));
}
